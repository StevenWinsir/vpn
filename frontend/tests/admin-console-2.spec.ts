import { expect, test, type Browser, type Page } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';

// Browser acceptance for the administrator console, part two (handoff_payment_account.md 9.5–9.7;
// R5-01 … R5-06): coupons, announcements and impersonation. It runs against the real API on a
// private PostgreSQL, started by scripts/test-payment-web.py.
type Fixture = {
  api: string;
  password: string;
  control: string;
  emails: Record<'ivan' | 'judy' | 'kyle' | 'lena' | 'boss', string>;
};

async function shot(page: Page, name: string) {
  const dir = `${process.env.PAYMENT_OUTPUTS ?? 'test-results'}/screens`;
  await mkdir(dir, { recursive: true });
  await page.screenshot({ path: `${dir}/${name}.png`, animations: 'disabled' });
}

let fixture: Fixture;
test.beforeAll(async () => {
  const filename = process.env.PAYMENT_FIXTURE;
  if (!filename?.startsWith('/tmp/vpn-payment-'))
    throw new Error('Private payment fixture required');
  fixture = JSON.parse(await readFile(filename, 'utf8')) as Fixture;
});

async function control(path: string, method = 'GET') {
  const response = await fetch(fixture.api + '/fixture/' + path, {
    method,
    headers: { 'X-Acceptance-Control': fixture.control },
  });
  if (!response.ok && response.status !== 204)
    throw new Error(`fixture ${path}: ${response.status}`);
  return response.status === 204 ? null : response.json();
}

async function signIn(page: Page, email: string) {
  await page.goto('/login');
  await page.getByLabel('邮箱地址').fill(email);
  await page.locator('input[type="password"]').fill(fixture.password);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
}

async function visitor(browser: Browser, email: string) {
  const context = await browser.newContext();
  const page = await context.newPage();
  await signIn(page, email);
  return { context, page };
}

const dialogs = (page: Page) => page.getByTestId('announcement');
async function acknowledgeAll(page: Page) {
  const shown = () =>
    dialogs(page)
      .waitFor({ state: 'visible', timeout: 5000 })
      .then(() => true)
      .catch(() => false);
  while (await shown()) {
    await page.getByRole('button', { name: '知道了' }).click();
    await expect(page.getByRole('button', { name: '知道了' }))
      .toBeHidden({ timeout: 3000 })
      .catch(() => undefined);
  }
}

