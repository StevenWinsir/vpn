test('coupons: create, generate, edit, disable, delete; a used one is only hidden and frozen', async ({
  page,
}) => {
  await signIn(page, fixture.emails.boss);
  await page.goto('/admin/console/coupons');
  await expect(page.getByRole('heading', { name: '管理后台' })).toBeVisible();
  const row = (code: string) => page.getByTestId('coupon-row').filter({ hasText: code });

  // Create by hand.
  await page.getByRole('button', { name: '新建优惠码' }).click();
  let modal = page.getByRole('dialog', { name: '新建优惠码' });
  await modal.getByLabel('优惠码', { exact: true }).fill('e2e-off10');
  await modal.getByLabel('备注').fill('端到端测试');
  await modal.getByLabel('减价比例（%）').fill('10');
  await modal.getByRole('button', { name: '保存' }).click();
  await expect(row('E2E-OFF10')).toContainText('立减 10%');
  await expect(row('E2E-OFF10')).toContainText('全部套餐');
  await expect(row('E2E-OFF10')).toContainText('有效');

  // A duplicate is refused with a reason.
  await page.getByRole('button', { name: '新建优惠码' }).click();
  modal = page.getByRole('dialog', { name: '新建优惠码' });
  await modal.getByLabel('优惠码', { exact: true }).fill('E2E-OFF10');
  await modal.getByRole('button', { name: '保存' }).click();
  await expect(modal.getByTestId('console-error')).toContainText('已存在');
  await modal.getByRole('button', { name: '取消' }).click();

  // Generated by the server: ten characters, fixed amount.
  await page.getByRole('button', { name: '新建优惠码' }).click();
  modal = page.getByRole('dialog', { name: '新建优惠码' });
  await modal.getByLabel('随机生成 10 位').check({ force: true });
  await modal.getByText('固定金额减价').click();
  await modal.getByLabel('减价金额（元）').fill('3');
  await modal.getByRole('button', { name: '保存' }).click();
  await expect(page.getByTestId('coupon-row').filter({ hasText: '立减 ¥3.00' })).toBeVisible();
  const codes = await page
    .getByTestId('coupon-row')
    .locator('td:first-child p')
    .first()
    .allInnerTexts();
  expect(codes.length).toBeGreaterThan(0);
  await shot(page, 'console-coupons');

  // Edit, then disable and enable again.
  await page.getByRole('button', { name: '编辑 E2E-OFF10' }).click();
  modal = page.getByRole('dialog', { name: /^编辑优惠码/ });
  await modal.getByLabel('备注').fill('改过的备注');
  await modal.getByRole('button', { name: '保存' }).click();
  await expect(row('E2E-OFF10')).toContainText('改过的备注');
  await page.getByRole('button', { name: '停用 E2E-OFF10' }).click();
  await expect(row('E2E-OFF10')).toContainText('已停用');
  await page.getByRole('button', { name: '启用 E2E-OFF10' }).click();
  await expect(row('E2E-OFF10')).toContainText('有效');

  // Never used: deleted for good.
  await page.getByRole('button', { name: '删除 E2E-OFF10' }).click();
  await page
    .getByRole('dialog', { name: /^删除优惠码/ })
    .getByRole('button', { name: '确认删除' })
    .click();
  await expect(row('E2E-OFF10')).toHaveCount(0);
  await page.getByLabel('显示已删除').check({ force: true });
  await expect(row('E2E-OFF10')).toHaveCount(0);
  await page.getByLabel('显示已删除').uncheck({ force: true });

  // Used by an order: its discount is frozen, and deleting only hides it.
  await page.getByRole('button', { name: '新建优惠码' }).click();
  modal = page.getByRole('dialog', { name: '新建优惠码' });
  await modal.getByLabel('优惠码', { exact: true }).fill('E2E-USED');
  await modal.getByLabel('减价比例（%）').fill('20');
  await modal.getByRole('button', { name: '保存' }).click();
  await expect(row('E2E-USED')).toBeVisible();
  await control(`coupon-used?code=E2E-USED&email=${encodeURIComponent(fixture.emails.lena)}`);
  await page.reload();
  await expect(row('E2E-USED')).toContainText('1 / 不限');
  await page.getByRole('button', { name: '编辑 E2E-USED' }).click();
  modal = page.getByRole('dialog', { name: /^编辑优惠码/ });
  await expect(modal).toContainText('折扣不能再修改');
  await expect(modal.getByLabel('减价比例（%）')).toBeDisabled();
  await modal.getByRole('button', { name: '取消' }).click();
  await page.getByRole('button', { name: '删除 E2E-USED' }).click();
  const confirm = page.getByRole('dialog', { name: /^删除优惠码/ });
  await expect(confirm).toContainText('已经被订单使用过');
  await confirm.getByRole('button', { name: '确认删除' }).click();
  await expect(row('E2E-USED')).toHaveCount(0);
  await page.getByLabel('显示已删除').check({ force: true });
  await expect(row('E2E-USED')).toContainText('已删除');
});

test('announcements reach users one by one and cannot be skipped; impersonation sees none', async ({
  page,
  browser,
}) => {
  await signIn(page, fixture.emails.boss);
  await page.goto('/admin/console/announcements');
  const row = (title: string) => page.getByTestId('announcement-row').filter({ hasText: title });
  const first = '第一条公告 E2E';
  const second = '第二条公告 E2E';
  const markup = '<script>window.__pwned = 1</script><b>粗体</b>\n第二行';

  async function draft(title: string, body: string) {
    await page.getByRole('button', { name: '新建公告' }).click();
    const modal = page.getByRole('dialog', { name: '新建公告' });
    await modal.getByLabel('标题').fill(title);
    await modal.getByLabel('正文（纯文本，保留换行）').fill(body);
    await expect(modal.getByTestId('announcement-preview')).toContainText(title);
    await modal.getByRole('button', { name: '保存草稿' }).click();
    await expect(row(title)).toContainText('草稿');
  }
  async function publish(title: string) {
    await page.getByRole('button', { name: `发布 ${title}` }).click();
    await page
      .getByRole('dialog', { name: '发布公告' })
      .getByRole('button', { name: '确认发布' })
      .click();
    await expect(row(title)).toContainText('已发布');
  }

  await draft(first, markup);
  await draft(second, '第二条正文');
  // A draft is private to administrators.
  const early = await visitor(browser, fixture.emails.ivan);
  await expect(dialogs(early.page)).toHaveCount(0);
  await early.context.close();
  // Edit before publishing; the published text is then locked (no edit button).
  await page.getByRole('button', { name: `编辑 ${second}` }).click();
  await page
    .getByRole('dialog', { name: '编辑草稿' })
    .getByLabel('正文（纯文本，保留换行）')
    .fill('第二条正文（定稿）');
  await page
    .getByRole('dialog', { name: '编辑草稿' })
    .getByRole('button', { name: '保存草稿' })
    .click();
  await publish(first);
  await publish(second);
  await expect(page.getByRole('button', { name: `编辑 ${first}` })).toHaveCount(0);
  await expect(page.getByRole('button', { name: `下线 ${first}` })).toBeVisible();
  await shot(page, 'console-announcements');

  // A user: oldest first, plain text, no way past except the button.
  const ivan = await visitor(browser, fixture.emails.ivan);
  const notice = ivan.page.getByRole('dialog', { name: first });
  await expect(notice).toBeVisible();
  await expect(ivan.page.getByTestId('announcement-body')).toHaveText(markup);
  expect(
    await ivan.page.evaluate(() => (window as unknown as { __pwned?: number }).__pwned),
  ).toBeUndefined();
  await expect(ivan.page.locator('[data-testid="announcement"] b')).toHaveCount(0);
  await expect(notice.getByRole('button', { name: /关闭|close/i })).toHaveCount(0);
  await ivan.page.keyboard.press('Escape');
  await expect(notice).toBeVisible();
  await ivan.page.mouse.click(5, 5);
  await expect(notice).toBeVisible();
  await shot(ivan.page, 'announcement-dialog');
  await ivan.page.reload();
  await expect(ivan.page.getByRole('dialog', { name: first })).toBeVisible();
  // A failing acknowledgement keeps the dialog and says so.
  await ivan.page.route('**/api/v1/me/announcements/*/ack', (route) => route.abort());
  await ivan.page.getByRole('button', { name: '知道了' }).click();
  await expect(ivan.page.getByRole('alert')).toBeVisible();
  await expect(ivan.page.getByRole('dialog', { name: first })).toBeVisible();
  await ivan.page.unroute('**/api/v1/me/announcements/*/ack');
  await ivan.page.getByRole('button', { name: '知道了' }).click();
  await expect(ivan.page.getByRole('dialog', { name: second })).toBeVisible();
  await expect(ivan.page.getByTestId('announcement-body')).toHaveText('第二条正文（定稿）');
  await ivan.page.getByRole('button', { name: '知道了' }).click();
  await expect(dialogs(ivan.page)).toHaveCount(0);
  // Gone for good: after a reload and on another device.
  await ivan.page.reload();
  await expect(ivan.page.getByRole('heading', { name: '总览' })).toBeVisible();
  await expect(dialogs(ivan.page)).toHaveCount(0);
  const ivan2 = await visitor(browser, fixture.emails.ivan);
  await ivan2.page.waitForTimeout(1500);
  await expect(dialogs(ivan2.page)).toHaveCount(0);
  await ivan2.context.close();
  await ivan.context.close();

  // Impersonating a user who still has both to read: nothing is shown, nothing can be written.
  const admin = await visitor(browser, fixture.emails.boss);
  await acknowledgeAll(admin.page); // an administrator is a user too
  await admin.page.goto('/admin/console/users?q=' + encodeURIComponent(fixture.emails.kyle));
  await admin.page.getByRole('button', { name: `查看 ${fixture.emails.kyle}` }).click();
  await admin.page
    .getByRole('dialog', { name: /^用户详情/ })
    .getByRole('button', { name: '模拟登录' })
    .click();
  const start = admin.page.getByRole('dialog', { name: /^模拟登录/ });
  await start.getByLabel('管理员密码').fill('wrong-' + fixture.password);
  await start.getByRole('button', { name: '开始模拟' }).click();
  await expect(start.getByTestId('console-error')).toContainText('管理员密码不正确');
  await start.getByLabel('管理员密码').fill(fixture.password);
  await start.getByRole('button', { name: '开始模拟' }).click();
  await expect(admin.page).toHaveURL(/\/dashboard$/);
  const banner = admin.page.getByTestId('impersonation-banner');
  await expect(banner).toContainText(fixture.emails.kyle);
  await expect(banner).toContainText('只读');
  await shot(admin.page, 'impersonation-banner');
  const seen = await admin.page.evaluate(async () => {
    const list = await (await fetch('/api/v1/me/announcements')).json();
    const write = await fetch('/api/v1/me/password', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ current_password: 'x', new_password: 'Another-Password-2026' }),
    });
    const ack = await fetch('/api/v1/me/announcements/00000000-0000-4000-8000-000000000000/ack', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: '{}',
    });
    const code = async (r: Response) => (await r.json()).error?.code;
    return {
      pending: list.announcements.length,
      write: [write.status, await code(write)],
      ack: [ack.status, await code(ack)],
    };
  });
  expect(seen).toEqual({
    pending: 0,
    write: [403, 'impersonation_read_only'],
    ack: [403, 'impersonation_read_only'],
  });
  await admin.page.waitForTimeout(1200);
  await expect(dialogs(admin.page)).toHaveCount(0);
  // The return cookie is HttpOnly, Strict and limited to the way back.
  const cookies = await admin.context.cookies();
  const way = cookies.find((c) => c.name === 'vpn_return');
  expect(way).toMatchObject({
    httpOnly: true,
    sameSite: 'Strict',
    path: '/api/v1/auth/impersonation/return',
  });
  expect(cookies.find((c) => c.name === 'vpn_refresh')?.path).toBe('/api/v1');
  // No console for the visited user.
  await admin.page.goto('/admin/console/users');
  await expect(admin.page.getByText('此页面仅对管理员开放')).toBeVisible();
  // Back to the administrator.
  await admin.page
    .getByTestId('impersonation-banner')
    .getByRole('button', { name: '返回管理员' })
    .click();
  await expect(admin.page).toHaveURL(/\/admin\/console\/users$/);
  await expect(admin.page.getByTestId('impersonation-banner')).toHaveCount(0);
  expect((await admin.context.cookies()).some((c) => c.name === 'vpn_return')).toBe(false);
  await acknowledgeAll(admin.page);
  await expect(admin.page.getByRole('form', { name: '用户筛选' })).toBeVisible();
  await admin.page.getByRole('button', { name: `查看 ${fixture.emails.kyle}` }).click();
  // Looking changed nothing: the visited user never signed in.
  await expect(admin.page.getByTestId('user-detail')).toContainText('从未登录');
  await admin.context.close();

  // Counts and the list of who confirmed.
  const judy = await visitor(browser, fixture.emails.judy);
  await acknowledgeAll(judy.page);
  await judy.context.close();
  await page.reload();
  await expect(row(first).getByTestId('read-count')).toContainText(/^3 \//);
  await page.getByRole('button', { name: `确认名单 ${first}` }).click();
  const reads = page.getByRole('dialog', { name: /已确认的用户/ });
  await expect(reads).toContainText(fixture.emails.ivan);
  await expect(reads).toContainText(fixture.emails.judy);
  await page.keyboard.press('Escape');

  // Taking them offline stops the pushing, for anyone who has not read them.
  await page.getByRole('button', { name: `下线 ${first}` }).click();
  await page
    .getByRole('dialog', { name: '下线公告' })
    .getByRole('button', { name: '确认下线' })
    .click();
  await expect(row(first)).toContainText('已下线');
  await page.getByRole('button', { name: `下线 ${second}` }).click();
  await page
    .getByRole('dialog', { name: '下线公告' })
    .getByRole('button', { name: '确认下线' })
    .click();
  await expect(row(second)).toContainText('已下线');
  const late = await visitor(browser, fixture.emails.lena);
  await late.page.waitForTimeout(1500);
  await expect(dialogs(late.page)).toHaveCount(0);
  await late.context.close();
  // A copy starts a new draft with the same text.
  await page.getByRole('button', { name: `复制 ${first}` }).click();
  const copy = page.getByRole('dialog', { name: '新建公告' });
  await expect(copy.getByLabel('标题')).toHaveValue(first);
  await copy.getByRole('button', { name: '取消' }).click();
});
