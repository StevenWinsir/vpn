// Regenerates every brand icon from the one source, brand/mark.svg (handoff_ui.md 7). Development
// only: the results are committed and CI never runs this. After replacing the logo run
//   npm run brand:icons
// (with PLAYWRIGHT_CHROME_PATH pointing at a local Chrome when Playwright has no browser of its
// own), then commit the changed files. scripts/theme.test.mjs checks that they match the source.
//
//   src/app/icon.svg                  the source, as is (modern browsers)
//   src/app/favicon.ico               16, 32 and 48 px PNGs in one ICO container
//   src/app/apple-icon.png            180 px on an opaque square (iOS home screen)
//   public/icons/icon-192.png, 512    for the web app manifest (Android home screen)
//   src/components/brand-mark-art.ts  the artwork for the BrandMark component
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const root = new URL('../', import.meta.url);
export const sourcePath = new URL('brand/mark.svg', root);
export const outputs = {
  svg: new URL('src/app/icon.svg', root),
  ico: new URL('src/app/favicon.ico', root),
  apple: new URL('src/app/apple-icon.png', root),
  manifest192: new URL('public/icons/icon-192.png', root),
  manifest512: new URL('public/icons/icon-512.png', root),
  art: new URL('src/components/brand-mark-art.ts', root),
};
export const icoSizes = [16, 32, 48];

// The source must be a square viewBox whose first element is the background tile; its fill is
// also the opaque background of the Apple icon.
export function parseSource(svg) {
  const viewBox = /<svg[^>]*\sviewBox="([^"]+)"/.exec(svg)?.[1];
  const body = /<svg[^>]*>([\s\S]*)<\/svg>\s*$/.exec(svg)?.[1];
  const tile = /^\s*<rect\b[^>]*\sfill="(#[0-9a-fA-F]{6})"/.exec(body ?? '')?.[1];
  if (!viewBox || !body || !tile) throw new Error('brand/mark.svg: unexpected structure');
  const [, , width, height] = viewBox.split(/\s+/).map(Number);
  if (width !== height) throw new Error('brand/mark.svg: the viewBox must be square');
  return { viewBox, body: body.trim().replace(/\n\s*/g, ''), tile };
}

export function artModule(svg) {
  const { viewBox, body } = parseSource(svg);
  return `// Generated by scripts/brand-icons.mjs from brand/mark.svg. Do not edit.
export const brandMarkViewBox = ${JSON.stringify(viewBox)};
export const brandMarkArt =
  ${JSON.stringify(body)};
`;
}

// An ICO file may carry PNG images directly (Windows Vista and every current browser).
export function ico(pngs) {
  const header = Buffer.alloc(6 + 16 * pngs.length);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  pngs.forEach(({ size, data }, index) => {
    const entry = 6 + 16 * index;
    header.writeUInt8(size >= 256 ? 0 : size, entry);
    header.writeUInt8(size >= 256 ? 0 : size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...pngs.map(({ data }) => data)]);
}

async function render(browser, svg, size, background) {
  const url = 'data:image/svg+xml;base64,' + Buffer.from(svg).toString('base64');
  const page = await browser.newPage({
    viewport: { width: size, height: size },
    deviceScaleFactor: 1,
  });
  await page.setContent(
    `<html><body style="margin:0;background:${background ?? 'transparent'}">` +
      `<img src="${url}" width="${size}" height="${size}" style="display:block"></body></html>`,
  );
  await page.locator('img').evaluate((img) => img.decode());
  const png = await page.screenshot({ omitBackground: !background });
  await page.close();
  return png;
}

async function main() {
  const { chromium } = await import('@playwright/test');
  const svg = readFileSync(sourcePath, 'utf8');
  const { tile } = parseSource(svg);
  const browser = await chromium.launch(
    process.env.PLAYWRIGHT_CHROME_PATH
      ? { executablePath: process.env.PLAYWRIGHT_CHROME_PATH }
      : {},
  );
  try {
    const pngs = [];
    for (const size of icoSizes) pngs.push({ size, data: await render(browser, svg, size) });
    writeFileSync(outputs.ico, ico(pngs));
    writeFileSync(outputs.apple, await render(browser, svg, 180, tile));
    writeFileSync(outputs.manifest192, await render(browser, svg, 192));
    writeFileSync(outputs.manifest512, await render(browser, svg, 512));
  } finally {
    await browser.close();
  }
  writeFileSync(outputs.svg, svg);
  writeFileSync(outputs.art, artModule(svg));
  console.log('brand icons regenerated from brand/mark.svg');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) await main();
