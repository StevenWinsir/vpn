/** Every piece of visible text of a document (the copy checks read this). */
export function legalTexts(doc: LegalDocument): string[] {
  const texts = [doc.title, doc.effective, doc.updated, ...doc.intro];
  for (const section of doc.sections) {
    texts.push(section.title);
    for (const block of section.blocks)
      texts.push(...(block.kind === 'p' ? [block.text] : block.items));
  }
  return texts;
}
