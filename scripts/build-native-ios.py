#!/usr/bin/env python3
"""Build the iOS client (handoff_app_ios.md round 1).

  --target xcconfig     validate apps/ios/.env (env-v1 rules, scripts/native_env.py) and write
                        apps/ios/Config/Generated.xcconfig, which both Info.plists read
  --target xcframework  gomobile-bind native/core/mobile (Go Core + pinned, patched Mihomo) into
                        apps/ios/Frameworks/AsterCore.xcframework and record its identity
  --target app          both of the above, then an unsigned build of the app and its tunnel
                        extension for the iOS Simulator (no simulator runtime is needed)

gomobile and gobind are built from the version native/core/go.mod pins, never a global
install, and the build refuses a tool that does not match apps/ios/toolchain.lock.json.
Nothing here signs anything or touches a device: there is no Apple team yet (P1).
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
import native_env  # noqa: E402
import prepare_mihomo  # noqa: E402

IOS = ROOT / 'apps/ios'
CORE = ROOT / 'native/core'
RUNTIME = ROOT / '.runtime/ios'
TOOLS = RUNTIME / 'bin'
FRAMEWORK = IOS / 'Frameworks/AsterCore.xcframework'
# The billing acceptance's test-only Core (tag asterlink_harness, handoff_app_ios.md 8.8): simulator slice only, in a
# directory no Xcode project references, so it can never be mixed with the production framework.
HARNESS_FRAMEWORK = RUNTIME / 'harness/AsterCore.xcframework'
GENERATED = IOS / 'Config/Generated.xcconfig'
LOCK = json.loads((IOS / 'toolchain.lock.json').read_text(encoding='utf-8'))
SLICES = ('ios-arm64', 'ios-arm64_x86_64-simulator')


def run(cmd, **kwargs):
    print('+ ' + ' '.join(str(c) for c in cmd), flush=True)
    subprocess.run([str(c) for c in cmd], check=True, **kwargs)


def xcconfig_value(value: str) -> str:
    """An .xcconfig treats '//' as the start of a comment, so 'https://host' would be cut
    to 'https:'. '$()' expands to nothing and breaks the pair without changing the value."""
    return value.replace('//', '/$()/')


def env_file() -> Path:
    # The release packager points this at .env.release.example (or the operator's own file).
    override = os.environ.get('ASTERLINK_IOS_ENV_FILE')
    if override:
        return Path(override)
    path = IOS / '.env'
    if path.exists():
        return path
    print('apps/ios/.env not found; using apps/ios/.env.example (public defaults)', flush=True)
    return IOS / '.env.example'


def write_xcconfig() -> dict:
    values = native_env.load_env_file(env_file())
    lines = ['// Generated by scripts/build-native-ios.py from the validated .env. Do not edit or commit.']
    for key, setting in (('APP_ENV', 'ASTER_APP_ENV'), ('API_BASE_URL', 'ASTER_API_BASE_URL'),
                         ('WEBSITE_BASE_URL', 'ASTER_WEBSITE_BASE_URL')):
        lines.append('%s = %s' % (setting, xcconfig_value(values[key])))
    GENERATED.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('wrote ' + str(GENERATED.relative_to(ROOT)), flush=True)
    return values


def build_gomobile():
    TOOLS.mkdir(parents=True, exist_ok=True)
    run(['go', 'build', '-o', str(TOOLS) + os.sep, 'golang.org/x/mobile/cmd/gomobile', 'golang.org/x/mobile/cmd/gobind'], cwd=CORE)
    info = subprocess.run(['go', 'version', '-m', str(TOOLS / 'gomobile')], capture_output=True, text=True, check=True).stdout
    match = re.search(r'mod\s+golang\.org/x/mobile\s+(\S+)', info)
    if not match or match.group(1) != LOCK['x_mobile']['version']:
        raise RuntimeError('gomobile was built from x/mobile %s, the lock says %s' % (match and match.group(1), LOCK['x_mobile']['version']))


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b''):
            digest.update(chunk)
    return digest.hexdigest()


def bind(app_version: str, harness: bool = False) -> dict:
    framework = HARNESS_FRAMEWORK if harness else FRAMEWORK
    slices = ('ios-arm64_x86_64-simulator',) if harness else SLICES
    patch = prepare_mihomo.prepare()
    revision = subprocess.run(['git', '-C', str(ROOT / 'native/third_party/Clash.Meta'), 'rev-parse', 'HEAD'],
                              capture_output=True, text=True, check=True).stdout.strip()
    build_gomobile()
    if framework.exists():
        shutil.rmtree(framework)
    framework.parent.mkdir(parents=True, exist_ok=True)
    ldflags = '-s -w -X asterlink/core/mobile.version=%s -X asterlink/core/mobile.mihomoRevision=%s' % (app_version, revision)
    bind_lock = LOCK['x_mobile']['ios_bind']
    env = dict(os.environ, PATH=str(TOOLS) + os.pathsep + os.environ.get('PATH', ''))
    run([TOOLS / 'gomobile', 'bind', '-target=' + ('iossimulator' if harness else bind_lock['targets']), '-iosversion', bind_lock['iosversion']]
        + (['-tags', 'asterlink_harness'] if harness else [])
        + ['-trimpath', '-ldflags', ldflags, '-o', framework, './mobile'], cwd=CORE, env=env)
    found = sorted(p.name for p in framework.iterdir() if p.is_dir())
    if found != sorted(slices):
        raise RuntimeError('unexpected xcframework slices %s, want %s' % (found, sorted(slices)))
    record = {
        'core_version': app_version,
        'mihomo_revision': revision,
        'mihomo_patch': patch,
        'x_mobile': LOCK['x_mobile']['version'],
        'harness': harness,
        'slices': {name: {'sha256': sha256(framework / name / 'AsterCore.framework/AsterCore'),
                          'bytes': (framework / name / 'AsterCore.framework/AsterCore').stat().st_size} for name in slices},
    }
    (framework.parent / 'core-build.json').write_text(json.dumps(record, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(record, indent=2), flush=True)
    return record


def build_app(configuration: str):
    run(['xcodebuild', 'build', '-project', IOS / 'AsterLink.xcodeproj', '-scheme', 'AsterLink',
         '-configuration', configuration, '-destination', 'generic/platform=iOS Simulator',
         '-derivedDataPath', RUNTIME / 'DerivedData', 'CODE_SIGNING_ALLOWED=NO'])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--target', choices=('xcconfig', 'xcframework', 'harness-framework', 'app'), required=True)
    parser.add_argument('--configuration', choices=('Debug', 'Release'), default='Debug')
    parser.add_argument('--app-version', default='0.1.0')
    parser.add_argument('--reuse-framework', action='store_true',
                        help='with --target app: keep an existing xcframework whose core-build.json is present')
    args = parser.parse_args()
    if args.target == 'harness-framework':
        bind(args.app_version, harness=True)
        return
    if args.target in ('xcconfig', 'app'):
        write_xcconfig()
    if args.target == 'xcframework' or (args.target == 'app' and not (args.reuse_framework and (FRAMEWORK.parent / 'core-build.json').exists())):
        bind(args.app_version)
    if args.target == 'app':
        build_app(args.configuration)


if __name__ == '__main__':
    try:
        main()
    except (native_env.EnvError, RuntimeError, subprocess.CalledProcessError) as error:
        sys.exit('build-native-ios: %s' % error)
